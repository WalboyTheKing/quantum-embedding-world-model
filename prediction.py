def create_demo_world():
    """
    Create a deterministic V1.0 test world.
    """

    world = SparseWorldModel(
        size=(8, 8, 8)
    )

    # Moving object
    world.update_sensor(
        5,
        2,
        1,
        "radar",
        2.4,
        0.80,
    )

    world.update_sensor(
        5,
        2,
        1,
        "lidar",
        1.0,
        0.92,
    )

    # Hot object
    world.update_sensor(
        6,
        4,
        2,
        "thermal",
        42.0,
        0.85,
    )

    # Central object
    world.update_sensor(
        4,
        4,
        2,
        "camera",
        0.8,
        0.95,
    )

    world.update_sensor(
        4,
        4,
        2,
        "lidar",
        1.0,
        0.98,
    )

    return world


