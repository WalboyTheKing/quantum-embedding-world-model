"""
Quantum-Embedding World Model
V1.0 - Prediction Layer

Purpose:
    Build a first testable prediction layer on top of the
    V0.7-V0.9 world-model substrate.

Architecture:

    3D World
        |
        +-- Sensor observations
        |
        +-- Spatial state
        |
        +-- Sparse compute
        |
        v
    Prediction
        |
        +-- Motion projection
        +-- Temperature projection
        +-- Confidence
        +-- Uncertainty

Important:
    Predictions are NOT observations.

    OBSERVED:
        directly written by sensors

    PREDICTED:
        generated by this module

The underlying world_model.py is not modified.
"""

from world_model import SparseWorldModel


class PredictionEngine:
    """
    First prediction layer for the Quantum-Embedding World Model.

    This version deliberately uses simple deterministic
    physical projections instead of pretending to have
    a learned AI model.
    """

    def __init__(self, world):
        self.world = world

    # ============================================================
    # BASIC HELPERS
    # ============================================================

    def _inside_bounds(self, x, y, z):
        """Check whether a coordinate is inside the 3D world."""

        sx, sy, sz = self.world.size

        return (
            0 <= x < sx
            and 0 <= y < sy
            and 0 <= z < sz
        )

    def _get_property(
        self,
        coordinate,
        property_name,
    ):
        """Safely retrieve one observed property."""

        x, y, z = coordinate

        result = self.world.query(
            x,
            y,
            z,
            property_name,
        )

        if not result:
            return None

        if result.get("state") == "UNKNOWN":
            return None

        return result

    # ============================================================
    # 1. MOTION PREDICTION
    # ============================================================

    def predict_motion(
        self,
        coordinate,
        direction,
        steps=1,
        confidence=0.7,
    ):
        """
        Project an observed moving object along a direction.

        Example:

            coordinate = (5, 2, 1)
            direction  = (1, 0, 0)
            steps      = 2

        Result:

            current  -> (5,2,1)
            future 1 -> (6,2,1)
            future 2 -> (7,2,1)

        The prediction is constrained by the 3D world bounds.
        """

        if steps < 1:
            raise ValueError(
                "steps must be >= 1"
            )

        if not 0.0 <= confidence <= 1.0:
            raise ValueError(
                "confidence must be between 0 and 1"
            )

        if not self._inside_bounds(
            *coordinate
        ):
            raise ValueError(
                "Starting coordinate is outside world bounds."
            )

        motion = self._get_property(
            coordinate,
            "motion",
        )

        if motion is None:
            return {
                "status": "UNKNOWN",
                "coordinate": coordinate,
                "reason": (
                    "No observed motion at this coordinate."
                ),
                "predictions": [],
            }

        dx, dy, dz = direction

        predictions = []

        for step in range(1, steps + 1):

            future = (
                coordinate[0] + dx * step,
                coordinate[1] + dy * step,
                coordinate[2] + dz * step,
            )

            if not self._inside_bounds(
                *future
            ):
                predictions.append({
                    "step": step,
                    "coordinate": future,
                    "state": "OUT_OF_BOUNDS",
                    "predicted": False,
                    "confidence": 1.0,
                    "uncertainty": 0.0,
                })

                continue

            # Confidence decreases slightly with prediction horizon.
            future_confidence = max(
                0.0,
                confidence
                * (1.0 - 0.10 * (step - 1)),
            )

            predictions.append({
                "step": step,
                "coordinate": future,
                "state": "PREDICTED",
                "predicted": True,
                "source_coordinate": coordinate,
                "observed_motion": motion.get(
                    "value"
                ),
                "confidence": future_confidence,
                "uncertainty": (
                    1.0 - future_confidence
                ),
            })

        return {
            "status": "PREDICTED",
            "coordinate": coordinate,
            "observed_motion": motion.get(
                "value"
            ),
            "predictions": predictions,
        }

    # ============================================================
    # 2. TEMPERATURE PREDICTION
    # ============================================================

    def predict_temperature(
        self,
        coordinate,
        delta_temperature,
        steps=1,
        confidence=0.7,
    ):
        """
        Project temperature from an observed temperature value.

        This is intentionally a simple deterministic projection.

        Example:

            current temperature = 42
            delta = +2
            steps = 3

            predictions:
                44
                46
                48
        """

        if steps < 1:
            raise ValueError(
                "steps must be >= 1"
            )

        if not 0.0 <= confidence <= 1.0:
            raise ValueError(
                "confidence must be between 0 and 1"
            )

        if not self._inside_bounds(
            *coordinate
        ):
            raise ValueError(
                "Coordinate is outside world bounds."
            )

        temperature = self._get_property(
            coordinate,
            "temperature",
        )

        if temperature is None:
            return {
                "status": "UNKNOWN",
                "coordinate": coordinate,
                "reason": (
                    "No observed temperature at this coordinate."
                ),
                "predictions": [],
            }

        current = temperature.get(
            "value"
        )

        predictions = []

        for step in range(1, steps + 1):

            predicted_temperature = (
                current
                + delta_temperature * step
            )

            future_confidence = max(
                0.0,
                confidence
                * (1.0 - 0.10 * (step - 1)),
            )

            predictions.append({
                "step": step,
                "coordinate": coordinate,
                "state": "PREDICTED",
                "predicted": True,
                "temperature": predicted_temperature,
                "confidence": future_confidence,
                "uncertainty": (
                    1.0 - future_confidence
                ),
            })

        return {
            "status": "PREDICTED",
            "coordinate": coordinate,
            "observed_temperature": current,
            "predictions": predictions,
        }

    # ============================================================
    # 3. FUTURE OCCUPANCY
    # ============================================================

    def predict_occupancy(
        self,
        coordinate,
        direction,
        steps=1,
        confidence=0.7,
    ):
        """
        Predict whether a moving object will occupy future voxels.

        This does not modify the world.

        It creates a prediction layer separate from observations.
        """

        motion_prediction = self.predict_motion(
            coordinate,
            direction,
            steps=steps,
            confidence=confidence,
        )

        if motion_prediction["status"] != "PREDICTED":
            return motion_prediction

        predictions = []

        for item in motion_prediction[
            "predictions"
        ]:

            if not item["predicted"]:
                predictions.append(item)
                continue

            future_coordinate = item[
                "coordinate"
            ]

            observed = self._get_property(
                future_coordinate,
                "matter",
            )

            if observed is None:
                occupancy_state = (
                    "UNKNOWN_FUTURE_OCCUPANCY"
                )
            else:
                value = observed.get(
                    "value"
                )

                if value is not None and value > 0:
                    occupancy_state = (
                        "OBSERVED_MATTER"
                    )
                else:
                    occupancy_state = (
                        "OBSERVED_FREE"
                    )

            predictions.append({
                **item,
                "future_occupancy": occupancy_state,
            })

        return {
            "status": "PREDICTED",
            "source_coordinate": coordinate,
            "predictions": predictions,
        }

    # ============================================================
    # 4. PREDICTION WITHOUT WORLD MUTATION
    # ============================================================

    def prediction_does_not_modify_world(
        self,
        prediction_function,
        *args,
        **kwargs,
    ):
        """
        Execute a prediction and verify that the sparse world
        itself has not changed.
        """

        before = len(
            self.world.voxels
        )

        result = prediction_function(
            *args,
            **kwargs,
        )

        after = len(
            self.world.voxels
        )

        return {
            "result": result,
            "world_modified": (
                before != after
            ),
            "voxels_before": before,
            "voxels_after": after,
        }

    # ============================================================
    # 5. PREDICTION SUMMARY
    # ============================================================

    def summary(self):
        """
        Return a compact description of the prediction layer.
        """

        return {
            "world_size": self.world.size,
            "observed_voxels": len(
                self.world.voxels
            ),
            "prediction_type": (
                "deterministic short-horizon projection"
            ),
            "world_mutation": False,
            "prediction_is_observation": False,
        }


