def run_tests():

    print("=" * 60)
    print("QUANTUM-EMBEDDING WORLD MODEL V1.0")
    print("PREDICTION LAYER")
    print("=" * 60)

    print()
    print("Creating prediction test world...")

    world = create_demo_world()

    engine = PredictionEngine(
        world
    )

    print()
    print("World size:", world.size)
    print(
        "Observed voxels:",
        len(world.voxels),
    )

    # ============================================================
    # TEST 1 - ENGINE
    # ============================================================

    summary = engine.summary()

    assert summary[
        "prediction_is_observation"
    ] is False

    print()
    print(
        "Prediction engine initialization test: PASS"
    )

    # ============================================================
    # TEST 2 - MOTION PREDICTION
    # ============================================================

    motion = engine.predict_motion(
        coordinate=(5, 2, 1),
        direction=(1, 0, 0),
        steps=2,
        confidence=0.80,
    )

    assert motion["status"] == (
        "PREDICTED"
    )

    assert len(
        motion["predictions"]
    ) == 2

    assert motion[
        "predictions"
    ][0]["coordinate"] == (
        6,
        2,
        1,
    )

    assert motion[
        "predictions"
    ][1]["coordinate"] == (
        7,
        2,
        1,
    )

    print(
        "Motion prediction test: PASS"
    )

    # ============================================================
    # TEST 3 - PREDICTION CONFIDENCE
    # ============================================================

    first_confidence = motion[
        "predictions"
    ][0]["confidence"]

    second_confidence = motion[
        "predictions"
    ][1]["confidence"]

    assert (
        second_confidence
        <= first_confidence
    )

    print(
        "Prediction confidence decay test: PASS"
    )

    # ============================================================
    # TEST 4 - TEMPERATURE
    # ============================================================

    temperature = engine.predict_temperature(
        coordinate=(6, 4, 2),
        delta_temperature=2.0,
        steps=3,
        confidence=0.80,
    )

    assert temperature[
        "status"
    ] == "PREDICTED"

    assert temperature[
        "predictions"
    ][0]["temperature"] == 44.0

    assert temperature[
        "predictions"
    ][1]["temperature"] == 46.0

    assert temperature[
        "predictions"
    ][2]["temperature"] == 48.0

    print(
        "Temperature prediction test: PASS"
    )

    # ============================================================
    # TEST 5 - UNKNOWN PREDICTION SOURCE
    # ============================================================

    unknown = engine.predict_motion(
        coordinate=(0, 0, 0),
        direction=(1, 0, 0),
        steps=2,
    )

    assert unknown[
        "status"
    ] == "UNKNOWN"

    assert len(
        unknown["predictions"]
    ) == 0

    print(
        "UNKNOWN prediction source test: PASS"
    )

    # ============================================================
    # TEST 6 - FUTURE OCCUPANCY
    # ============================================================

    occupancy = engine.predict_occupancy(
        coordinate=(5, 2, 1),
        direction=(1, 0, 0),
        steps=2,
        confidence=0.80,
    )

    assert occupancy[
        "status"
    ] == "PREDICTED"

    assert len(
        occupancy["predictions"]
    ) == 2

    print(
        "Future occupancy prediction test: PASS"
    )

    # ============================================================
    # TEST 7 - OUT OF BOUNDS
    # ============================================================

    out_of_bounds = engine.predict_motion(
        coordinate=(7, 7, 7),
        direction=(1, 0, 0),
        steps=2,
    )

    assert out_of_bounds[
        "status"
    ] == "UNKNOWN"

    print(
        "Out-of-bounds source test: PASS"
    )

    # ============================================================
    # TEST 8 - PREDICTION DOES NOT MODIFY WORLD
    # ============================================================

    before = len(
        world.voxels
    )

    check = engine.prediction_does_not_modify_world(
        engine.predict_temperature,
        (6, 4, 2),
        1.0,
        3,
        0.8,
    )

    after = len(
        world.voxels
    )

    assert before == after

    assert check[
        "world_modified"
    ] is False

    print(
        "Prediction immutability test: PASS"
    )

    # ============================================================
    # TEST 9 - PREDICTION != OBSERVATION
    # ============================================================

    predicted_coordinate = motion[
        "predictions"
    ][0]["coordinate"]

    assert (
        predicted_coordinate
        not in world.voxels
    )

    print(
        "Prediction != observation test: PASS"
    )

    # ============================================================
    # TEST 10 - UNCERTAINTY
    # ============================================================

    prediction = motion[
        "predictions"
    ][0]

    assert (
        prediction["uncertainty"]
        == 1.0
        - prediction["confidence"]
    )

    print(
        "Prediction uncertainty test: PASS"
    )

    # ============================================================
    # FINAL SUMMARY
    # ============================================================

    print()
    print("-" * 60)
    print("PREDICTION SUMMARY")
    print("-" * 60)

    print(
        "Observed voxels       :",
        len(world.voxels),
    )

    print(
        "Motion source         :",
        (5, 2, 1),
    )

    print(
        "Predicted positions   :",
        [
            item["coordinate"]
            for item in motion[
                "predictions"
            ]
            if item["predicted"]
        ],
    )

    print(
        "Observed temperature  :",
        temperature[
            "observed_temperature"
        ],
    )

    print(
        "Predicted temperatures:",
        [
            item["temperature"]
            for item in temperature[
                "predictions"
            ]
        ],
    )

    print()
    print("=" * 60)
    print("V1.0 TEST COMPLETE")
    print("=" * 60)

    print()
    print("All V1.0 tests passed.")

    print()
    print("Architecture validated:")
    print("  [OK] Short-horizon motion prediction")
    print("  [OK] Temperature prediction")
    print("  [OK] Prediction confidence")
    print("  [OK] Prediction uncertainty")
    print("  [OK] Future occupancy analysis")
    print("  [OK] UNKNOWN source handling")
    print("  [OK] 3D bounds handling")
    print("  [OK] Prediction does not mutate world")
    print("  [OK] Prediction != observation")
    print("  [OK] Sparse world preserved")

    print("=" * 60)


